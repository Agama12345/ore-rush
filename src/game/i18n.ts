export function t(key: string, vars?: Record<string, string | number>) {
  const entry = D[key];
  let text = entry ? entry[current] : key;
  if (vars) for (const [k, v] of Object.entries(vars)) text = text.replace(`{${k}}`, String(v));
  return text;
}

